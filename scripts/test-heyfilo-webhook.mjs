#!/usr/bin/env node
/**
 * Local HMAC simulator for the heyfilo webhook (@heyfilo/sdk).
 *
 * Signs `${timestamp}.${rawBody}` with HEYFILO_SECRET exactly like heyfilo does
 * and posts to the receiver, exercising:
 *   - connection.test           (happy path)
 *   - post.created              (happy path — SDK downloads the image URLs!)
 *   - bad-signature             (negative — expect 400 unauthorized)
 *   - stale-timestamp           (negative — expect 400 stale-timestamp)
 *
 * Usage:
 *   node scripts/test-heyfilo-webhook.mjs                 # run all cases
 *   node scripts/test-heyfilo-webhook.mjs post.created    # one case
 *   URL=http://localhost:3000/api/heyfilo-webhook \
 *     HEYFILO_SECRET=... node scripts/test-heyfilo-webhook.mjs
 *
 * The signing contract MUST match dist/core/verify.js:
 *   signature = "sha256=" + HMAC_SHA256(secret, `${timestamp}.${body}`)  (hex)
 *   headers:  x-heyfilo-event-id, x-heyfilo-timestamp, x-heyfilo-signature
 *
 * NOTE: post.created makes the SDK DOWNLOAD heroImage + every inlineImages[]
 * URL — a failed download is FATAL (post not created, 500). The defaults below
 * use real, reachable placeholder images so the happy path works online.
 */
import crypto from "node:crypto";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

/** Minimal .env.local loader so HEYFILO_SECRET need not be exported manually. */
function loadEnvLocal() {
  try {
    const raw = readFileSync(path.join(ROOT, ".env.local"), "utf8");
    for (const line of raw.split("\n")) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
      if (m && !(m[1] in process.env)) {
        process.env[m[1]] = m[2].replace(/^["']|["']$/g, "");
      }
    }
  } catch {
    /* no .env.local — rely on real env */
  }
}
loadEnvLocal();

const URL_TARGET =
  process.env.URL || "http://localhost:3000/api/heyfilo-webhook";
const SECRET = process.env.HEYFILO_SECRET || "";
if (!SECRET) {
  console.error("HEYFILO_SECRET is not set (env or .env.local). Aborting.");
  process.exit(1);
}

function sign(secret, timestamp, body) {
  const hex = crypto
    .createHmac("sha256", Buffer.from(secret, "utf8"))
    .update(`${timestamp}.${body}`, "utf8")
    .digest("hex");
  return `sha256=${hex}`;
}

let counter = 0;
function uniqueId(prefix) {
  // Avoid Date.now collisions across rapid runs; eventId drives idempotency.
  return `${prefix}-${process.pid}-${++counter}-${crypto
    .randomBytes(4)
    .toString("hex")}`;
}

function postCreatedPayload() {
  const id = uniqueId("post");
  return {
    event: "post.created",
    eventId: uniqueId("evt"),
    postId: id,
    version: "1.0",
    timestamp: new Date().toISOString(),
    post: {
      title: "Test Post from heyfilo simulator",
      slug: "test-post-from-heyfilo-simulator",
      excerpt: "A short excerpt for the simulated post.",
      body: '<p>Hello from the simulator.</p><p><img src="https://placehold.co/300x200.png" alt="inline"></p>',
      bodyFormat: "html",
      tags: ["testing", "heyfilo"],
      categories: ["Engineering"],
      author: {
        name: "Sim Author",
        bio: "Generated by the local simulator.",
        avatarUrl: "https://placehold.co/96x96.png",
      },
      seo: {
        metaTitle: "Test Post (SEO title)",
        metaDescription: "Test Post SEO description.",
      },
      heroImage: { url: "https://placehold.co/600x400.png", alt: "hero" },
      inlineImages: [
        { url: "https://placehold.co/300x200.png", alt: "inline" },
      ],
      publishedAt: new Date().toISOString(),
    },
  };
}

function connectionTestPayload() {
  return {
    event: "connection.test",
    eventId: uniqueId("evt"),
    version: "1.0",
    timestamp: new Date().toISOString(),
    message: "ping",
  };
}

/** Send one signed request. `mutate` lets a case tamper with sig/timestamp. */
async function send(name, payload, mutate = {}) {
  const body = JSON.stringify(payload);
  const timestamp =
    mutate.timestamp ?? String(Math.floor(Date.now() / 1000));
  let signature = sign(SECRET, timestamp, body);
  if (mutate.badSignature) signature = "sha256=" + "0".repeat(64);

  const headers = {
    "content-type": "application/json",
    "x-heyfilo-event-type": payload.event,
    "x-heyfilo-event-id": payload.eventId || "",
    "x-heyfilo-timestamp": timestamp,
    "x-heyfilo-signature": signature,
  };

  let res, text;
  try {
    res = await fetch(URL_TARGET, { method: "POST", headers, body });
    text = await res.text();
  } catch (err) {
    console.log(`\n[${name}] REQUEST FAILED: ${err.message}`);
    return { ok: false };
  }

  const expect = mutate.expectStatus;
  const pass = expect == null ? res.ok : res.status === expect;
  console.log(
    `\n[${name}] ${pass ? "PASS" : "FAIL"} — HTTP ${res.status}` +
      (expect != null ? ` (expected ${expect})` : "")
  );
  console.log(`  ${text.slice(0, 300)}`);
  return { ok: pass };
}

const CASES = {
  "connection.test": () =>
    send("connection.test", connectionTestPayload()),
  "post.created": () => send("post.created", postCreatedPayload()),
  "bad-signature": () =>
    send("bad-signature", connectionTestPayload(), {
      badSignature: true,
      expectStatus: 400,
    }),
  "stale-timestamp": () =>
    send("stale-timestamp", connectionTestPayload(), {
      // 10 minutes old — beyond the 300s tolerance.
      timestamp: String(Math.floor(Date.now() / 1000) - 600),
      expectStatus: 400,
    }),
};

async function main() {
  const arg = process.argv[2];
  console.log(`Target: ${URL_TARGET}`);
  const names = arg ? [arg] : Object.keys(CASES);
  let allPass = true;
  for (const name of names) {
    const run = CASES[name];
    if (!run) {
      console.error(`Unknown case "${name}". Choices: ${Object.keys(CASES).join(", ")}`);
      process.exit(2);
    }
    const { ok } = await run();
    allPass = allPass && ok;
  }
  console.log(`\n${allPass ? "ALL PASS" : "SOME FAILED"}`);
  process.exit(allPass ? 0 : 1);
}

main();
